            // Toggle current item
            if (!isOpen) {
                item.classList.add('active');
                content.style.maxHeight = content.scrollHeight + 'px';

                // Ensure clicked header stays in view after expanding
                setTimeout(() => {
                    header.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }, 300); // Match transition time
            }
        });
    });
