                btn.addEventListener('click', openModal);
            });

            // close
            span.addEventListener('click', function() {
                modal.style.display = 'none';
            });

            // clode modal when clikc outside
            window.onclick = function(event) {
                if (event.target == modal) {
                    modal.style.display = 'none';
