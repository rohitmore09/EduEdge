            // Map scaling between 1 and number of .plans
            const plans = document.querySelectorAll(".plans");
            const scaleMax = gsap.utils.mapRange(1, plans.length - 1, 0.8, 1);
            const time = 2;

            // Initial setup
            gsap.set(plans, {
                y: (index) => 10 * index,
                transformStyle: "preserve-3d",
                //   transformPerspective: 1000,
                transformOrigin: "top center",
            });

            // Scroll-triggered timeline
            const tl = gsap.timeline({
                scrollTrigger: {
                    trigger: ".card-stack",
                    start: "top 10%",
                    end: () => `${window.innerHeight * 5}px top`,
                    scrub: true,
                    pin: true,
                    pinSpace: false,
                }
            });

            // Animate .plans from below the viewport into place
            tl.from(plans, {
                y: () => window.innerHeight,
                duration: time / 2,
                stagger: time,
            });

            // Rotate and scale all except the last child
            tl.to(".plans:not(:last-child)", {
                rotationX: -20,
                scale: (index) => scaleMax(index),
                stagger: {
                    each: time,
                }
            }, time);
        }

        // testimonial slider
